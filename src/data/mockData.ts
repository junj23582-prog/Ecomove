export function formatLocationDetail(loc: LocationSelection): string {
  const parts: string[] = [];
  if (loc.housingName?.trim()) parts.push(loc.housingName.trim());
  if (loc.gang?.trim()) parts.push(loc.gang.trim());
  const rtVal = loc.rt?.trim();
  const rwVal = loc.rw?.trim();
  if (rtVal && rwVal) {
    parts.push(`RT ${rtVal}/RW ${rwVal}`);
  } else if (rtVal) {
    parts.push(`RT ${rtVal}`);
  } else if (rwVal) {
    parts.push(`RW ${rwVal}`);
  }
  if (loc.houseNumber?.trim()) parts.push(loc.houseNumber.trim());
  return parts.join(' · ');
}

